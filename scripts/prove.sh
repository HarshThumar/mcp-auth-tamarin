    args=(--prove "$model")
    if [[ "$flag" != "-" ]]; then
      IFS=',' read -ra flags <<<"$flag"
      for f in "${flags[@]}"; do args+=("-D=$f"); done
    fi
    echo "== tamarin-prover ${args[*]}"
